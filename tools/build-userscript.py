#!/usr/bin/env python3
"""Builds dist/spotify-mobile.user.js from app/src/main/assets/wrap/inject.css and inject.js.

The userscript gives open.spotify.com the same phone layout as the app, inside your own browser
(Firefox with Violentmonkey or Tampermonkey, in "Desktop site" mode). Run from anywhere:
    python3 tools/build-userscript.py            # normal
    python3 tools/build-userscript.py --debug    # adds a label showing what the script sees
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ASSETS = ROOT / "app/src/main/assets/wrap"
OUT = ROOT / "dist/spotify-mobile.user.js"
VERSION = "0.2.3"
DEBUG = "--debug" in sys.argv

HEADER = f"""// ==UserScript==
// @name         Spotify Mobile Layout
// @namespace    spotify-wrapper
// @version      {VERSION}
// @description  Phone-friendly layout for open.spotify.com in the browser's Desktop site mode.
// @match        https://open.spotify.com/*
// @grant        none
// @run-at       document-idle
// @noframes
// ==/UserScript==
// Generated by tools/build-userscript.py from app/src/main/assets/wrap/inject.css and inject.js.
// Edit those, not this file.
"""

css = (ASSETS / "inject.css").read_text(encoding="utf-8")
js = (ASSETS / "inject.js").read_text(encoding="utf-8")
OUT.parent.mkdir(exist_ok=True)
prelude = "window.__WRAP_CSS__ = " + json.dumps(css) + ";\nwindow.__WRAP_VERSION__ = " + json.dumps(VERSION) + ";\n"
if DEBUG:
    prelude += "window.__WRAP_DEBUG__ = true;\n"
OUT.write_text(HEADER + prelude + js, encoding="utf-8")
print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)")
